/// A UI action.
///
/// Used internally as the result of input events.
///
/// Also generated by interaction with [`MouseArea`]s.
///
/// The ordering of variants is used in the help screen.
#[derive(Debug, Clone, Copy, Deserialize, PartialEq, PartialOrd)]
pub enum Action {
    Help,
    Exit,
    MoveUp,
    MoveDown,
    PageUp,
    PageDown,
    MoveFirst,
    MoveLast,
    ToggleMute,
    ToggleHiddenInstance,
    ToggleHiddenPermanent,
    SetRelativeVolume(f32),
    SetDefault,
    ActivateDropdown,
    CloseDropdown,
    TabLeft,
    TabRight,
    SelectTab(usize),
    SetAbsoluteVolume(f32),
    #[serde(skip_deserializing)]
    SelectObject(ObjectId),
    #[serde(skip_deserializing)]
    SetTarget(view::Target),
    // This can be used to delete a default keybinding - make it do nothing.
    Nothing,
}

impl std::fmt::Display for Action {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Action::SelectTab(tab) => write!(f, "Select {tab} tab"),
            Action::MoveUp => write!(f, "Move cursor up"),
            Action::MoveDown => write!(f, "Move cursor down"),
            Action::PageUp => write!(f, "Move cursor up a page"),
            Action::PageDown => write!(f, "Move cursor down a page"),
            Action::MoveFirst => write!(f, "Move cursor to first item"),
            Action::MoveLast => write!(f, "Move cursor to last item"),
            Action::TabLeft => write!(f, "Select previous tab"),
            Action::TabRight => write!(f, "Select next tab"),
            Action::CloseDropdown => write!(f, "Close menu"),
            Action::ActivateDropdown => write!(f, "Open menu"),
            Action::SelectObject(object_id) => {
                write!(f, "Select object {object_id:?}")
            }
            Action::SetTarget(_) => write!(f, "Set target"),
            Action::ToggleMute => write!(f, "Toggle mute"),
            Action::ToggleHiddenInstance => {
                write!(f, "Hide/show for this instance only")
            }
            Action::ToggleHiddenPermanent => {
                write!(f, "Hide/show permanently, synced to other instances")
            }
            Action::SetAbsoluteVolume(vol) => {
                write!(f, "Set volume to {}%", Self::format_percentage(*vol))
            }
            Action::SetRelativeVolume(vol) => {
                Self::format_relative_volume(f, *vol)
            }
            Action::SetDefault => write!(f, "Set default"),
            Action::Help => write!(f, "Show/hide help"),
            Action::Exit => write!(f, "Exit wiremix"),
            Action::Nothing => write!(f, "Nothing"),
        }
    }
}

impl Action {
    // The help menu doesn't track how many lines actually fit on screen (it's
    // computed inline at render time from the terminal area), so PageUp/
    // PageDown there just jump a fixed number of lines rather than a true
    // page - close enough for a scrollable overlay, and avoids threading
    // layout information through for a fairly minor case.
    const HELP_PAGE_STEP: u16 = 10;

    fn format_percentage(vol: f32) -> u16 {
        (vol * 100.0).trunc() as u16
    }

    fn format_relative_volume(
        f: &mut std::fmt::Formatter<'_>,
        vol: f32,
    ) -> std::fmt::Result {
        match vol {
            0.01 => write!(f, "Increment volume"),
            -0.01 => write!(f, "Decrement volume"),
            v if v >= 0.0 => {
                write!(f, "Increase volume by {}%", Self::format_percentage(v))
            }
            v => {
                write!(f, "Decrease volume by {}%", Self::format_percentage(-v))
            }
        }
    }
}

struct Tab {
    title: String,
    list: ObjectList,
}

impl Tab {
    fn new(title: String, list: ObjectList) -> Self {
        Self { title, list }
    }
}

impl From<TabKind> for Tab {
    fn from(tab_kind: TabKind) -> Tab {
        match tab_kind {
            TabKind::Playback => Tab::new(
                String::from("Playback"),
                ObjectList::new(ListKind::Node(view::NodeKind::Playback), None),
            ),
            TabKind::Recording => Tab::new(
                String::from("Recording"),
                ObjectList::new(
                    ListKind::Node(view::NodeKind::Recording),
                    None,
                ),
            ),
            TabKind::Output => Tab::new(
                String::from("Output Devices"),
                ObjectList::new(
                    ListKind::Node(view::NodeKind::Output),
                    Some(DeviceKind::Sink),
                ),
            ),
            TabKind::Input => Tab::new(
                String::from("Input Devices"),
                ObjectList::new(
                    ListKind::Node(view::NodeKind::Input),
                    Some(DeviceKind::Source),
                ),
            ),
            TabKind::Configuration => Tab::new(
                String::from("Configuration"),
                ObjectList::new(ListKind::Device, None),
            ),
        }
    }
}

// Mouse events matching one of the MouseEventKinds within the Rect will
// perform the Actions.
pub type MouseArea =
    (Rect, SmallVec<[MouseEventKind; 4]>, SmallVec<[Action; 4]>);

/// Handles the main UI for the application.
///
/// This runs the main loop to process PipeWire events and terminal input and
/// to render the main tabs of the application.
pub struct App<'a> {
    /// If set, tells the main loop it's time to exit
    exit: bool,
    /// wirehose handle, for sending commands
    wirehose: &'a dyn CommandSender,
    /// [`Event`](`crate::event::Event`) channel
    rx: mpsc::Receiver<Event>,
    /// An error message to return on exit
    error_message: Option<String>,
    /// The main tabs
    tabs: Vec<Tab>,
    /// The index of the currently-visible tab
    current_tab_index: usize,
    /// Areas populated during rendering which define actions corresponding to
    /// mouse activity
    mouse_areas: Vec<MouseArea>,
    /// wirehose has received all initial information
    is_ready: bool,
    /// The current PipeWire state
    state: State,
    /// Does the view need to be updated with the current PipeWire state?
    state_dirty: bool,
    /// A rendering view based on the current PipeWire state
    view: View<'a>,
    /// The application configuration
    config: Config,
    /// The row on which the mouse is being dragged. While the left mouse
    /// button is held down, this is used in place of the real row to allow the
    /// mouse to move on the vertical axis during horizontal dragging.
    drag_row: Option<u16>,
    /// Position in help text (None if not showing help)
    help_position: Option<u16>,
    /// Object IDs that are currently visible (including any display
    /// dependencies)
    visible_objects: HashSet<ObjectId>,
    /// Object IDs hidden for this instance only - never persisted, never
    /// synced to other instances. Hidden objects sink to the bottom of
    /// their list and are excluded from capture.
    hidden_instance: HashSet<ObjectId>,
    /// Durable matchers for permanently-hidden items, loaded from (and
    /// saved back to) `hidden_state_path`. Source of truth for
    /// `hidden_permanent` - re-evaluated against live state whenever it
    /// changes, since object IDs in `hidden_permanent` don't survive a
    /// restart but these matchers do.
    hidden_permanent_matchers: Vec<MatchCondition>,
    /// Object IDs currently matching a `hidden_permanent_matchers` entry.
    /// Recomputed from `hidden_permanent_matchers` whenever state changes,
    /// same recompute rather than incremental-update-per-event choice
    /// `capturable_objects` etc. don't need since matcher content can
    /// change independently of any single state event. Excluded from
    /// capture and sinks below `hidden_instance` in the list, same as
    /// instance-hidden objects but ranked lower.
    hidden_permanent: HashSet<ObjectId>,
    /// Where to load/save `hidden_permanent_matchers`. `None` if
    /// `HiddenState::default_path()` couldn't resolve one (no `$HOME`) -
    /// permanent hide then behaves like instance hide for the rest of the
    /// session, since there's nowhere to persist it.
    hidden_state_path: Option<PathBuf>,
    /// Callback for peak ballistics.
    peak_processor: Arc<dyn PeakProcessor>,
    /// Objects eligible for capture.
    capturable_objects: HashSet<ObjectId>,
    /// Objects currently being captured.
    capturing_objects: HashSet<ObjectId>,
    /// Index into the sorted eligible-objects list where the next capture
    /// rotation window should start. Only meaningful when
    /// config.max_concurrent_captures is set.
    capture_rotation_start: usize,
    /// Rendered frames elapsed since the capture rotation window last
    /// advanced. See ROTATION_FRAME_INTERVAL - deliberately a frame count,
    /// not a wall-clock duration.
    frames_since_rotation: u32,
}

macro_rules! current_list {
    ($self:expr) => {
        $self.tabs[$self.current_tab_index].list
    };
}

impl<'a> App<'a> {
    pub fn new(
        wirehose: &'a dyn CommandSender,
        rx: mpsc::Receiver<Event>,
        config: Config,
    ) -> Self {
        let tabs = config.tabs.iter().copied().map(Tab::from).collect();

        // Update peaks with VU-meter-style ballistics
        let peak_processor = |new_peak, current_peak, samples, rate| {
            // Attack/release time of 300 ms
            let time_constant = 0.3;
            let coef =
                1.0 - (-(samples as f32) / (time_constant * rate as f32)).exp();

            current_peak + (new_peak - current_peak) * coef
        };

        let state = State::default();

        App {
            exit: false,
            wirehose,
            rx,
            error_message: None,
            tabs,
            current_tab_index: config.tab,
            mouse_areas: Vec::new(),
            is_ready: false,
            state,
            state_dirty: false,
            view: View::new(wirehose),
            config,
            drag_row: None,
            help_position: None,
            visible_objects: HashSet::new(),
            hidden_instance: HashSet::new(),
            hidden_permanent_matchers: Vec::new(),
            hidden_permanent: HashSet::new(),
            hidden_state_path: None,
            peak_processor: Arc::new(peak_processor),
            capturable_objects: HashSet::new(),
            capturing_objects: HashSet::new(),
            capture_rotation_start: 0,
            frames_since_rotation: 0,
        }
    }

    /// Loads persisted permanently-hidden-item matchers from `path` and
    /// remembers `path` for future saves. Call once after construction and
    /// before [`Self::run`] - matching entries won't take effect against
    /// live nodes until the first state update recomputes
    /// `hidden_permanent`. A no-op if `path` is `None` (no resolvable
    /// state directory) or nothing has ever been saved there yet.
    pub fn load_hidden_state(&mut self, path: Option<PathBuf>) {
        let Some(path) = path else {
            return;
        };

        if let Ok(hidden_state) = HiddenState::load(&path) {
            self.hidden_permanent_matchers = hidden_state.hidden;
        }

        self.hidden_state_path = Some(path);
    }

    /// Re-evaluates `hidden_permanent_matchers` against every currently
    /// live node, since a node's `object_id` in `hidden_permanent` doesn't
    /// survive a restart but the matchers persisted to
    /// `hidden_state_path` do - and matcher content can change (a
    /// permanent hide/unhide) independently of any single state event, so
    /// this can't be updated incrementally the way `capturable_objects`
    /// etc. are.
    fn recompute_hidden_permanent(&mut self) {
        self.hidden_permanent = self
            .state
            .nodes
            .values()
            .filter(|node| {
                self.hidden_permanent_matchers
                    .iter()
                    .any(|matcher| matcher.matches(&self.state, *node))
            })
            .map(|node| node.object_id)
            .collect();
    }

    /// Persists `hidden_permanent_matchers` to `hidden_state_path`. A
    /// no-op if no path was resolved at startup. Errors are swallowed -
    /// same tradeoff `HiddenState::save`'s own doc comment already
    /// describes for a racing concurrent save, extended here to cover
    /// any other save failure (e.g. a read-only filesystem): permanent
    /// hide still works for the rest of this session even if it can't be
    /// written to disk, rather than crashing the whole UI over it.
    fn save_hidden_state(&self) {
        let Some(path) = &self.hidden_state_path else {
            return;
        };

        let hidden_state = HiddenState {
            hidden: self.hidden_permanent_matchers.clone(),
        };
        let _ = hidden_state.save(path);
    }

    /// Reacts to `hidden_state_path` having changed on disk - most likely
    /// another wiremix instance's own `save_hidden_state()`, delivered via
    /// the inotify watch in `wirehose::session` (see its doc comment for
    /// why the watch itself lives there). Deliberately does not call
    /// `save_hidden_state()` itself: this instance is *reading* a change
    /// something else already wrote, not originating one - re-saving here
    /// would just write the same content straight back and cause another
    /// spurious watch trigger for every real one.
    ///
    /// The content comparison below also means saving our own change here
    /// harmlessly no-ops if this fires for our own just-written file
    /// (which it will, since the watch is on the directory, not scoped by
    /// writer) - not required for correctness the way the equivalent guard
    /// was for the PipeWire-metadata design this replaced (no re-save here
    /// means no risk of an actual feedback loop either way), but it's
    /// nearly free and avoids a redundant recompute + capture-diff pass.
    fn apply_file_hidden_state_change(&mut self) {
        let Some(path) = self.hidden_state_path.clone() else {
            return;
        };

        let Ok(hidden_state) = HiddenState::load(&path) else {
            return;
        };

        let current_json =
            serde_json::to_string(&self.hidden_permanent_matchers).ok();
        let new_json = serde_json::to_string(&hidden_state.hidden).ok();
        if current_json == new_json {
            return;
        }

        self.hidden_permanent_matchers = hidden_state.hidden;
        self.recompute_hidden_permanent();
        self.state_dirty = true;

        let need_to_stop: Vec<_> = self
            .capturing_objects
            .iter()
            .copied()
            .filter(|id| self.hidden_permanent.contains(id))
            .collect();
        for object_id in need_to_stop {
            self.stop_capture(object_id);
        }

        let need_to_start: Vec<_> = self
            .capturable_objects
            .iter()
            .copied()
            .filter(|id| !self.capturing_objects.contains(id))
            .collect();
        for object_id in need_to_start {
            self.start_capture(object_id);
        }
    }

    pub fn run(mut self, terminal: &mut DefaultTerminal) -> Result<()> {
        // Wait until we've received all initial data from PipeWire
        let _ = terminal.draw(|frame| {
            frame.render_widget(Line::from("Initializing..."), frame.area());
        });
        while !self.exit && !self.is_ready {
            let _ = self.handle_events(None);
        }

        let mut pacer = RenderPacer::new(self.config.fps);

        // Did we handle any events and thus need to re-render?
        let mut needs_render = true;

        while !self.exit {
            // Update view if needed
            if self.state_dirty {
                self.recompute_hidden_permanent();
                self.view = View::from(
                    self.wirehose,
                    &self.state,
                    &self.config.names,
                    &self.config.filters,
                    &self.hidden_instance,
                    &self.hidden_permanent,
                );
            }
            self.state_dirty = false;

            let frame = terminal.get_frame();
            current_list!(self).update(
                frame.area(),
                &self.view,
                self.config.show_dividers,
            );

            let new_visible_objects = current_list!(self).visible_objects(
                &frame.area(),
                &self.view,
                self.config.show_dividers,
            );
            if new_visible_objects != self.visible_objects {
                needs_render = true;
                self.visible_objects = new_visible_objects;
                self.update_capturing();
            }

            if needs_render && pacer.is_time_to_render() {
                needs_render = false;

                // Tied to the render cadence itself (see
                // ROTATION_FRAME_INTERVAL) rather than a wall-clock timer of
                // its own: rotate_capturing() is only ever called here, in
                // step with an actually-rendered frame, so counting frames
                // there is exact rather than an approximation of one.
                self.rotate_capturing();

                self.mouse_areas.clear();

                terminal.draw(|frame| {
                    self.draw(frame);
                })?;
            }

            needs_render |= self.handle_events(
                // If there's no fps limit, we definitely rendered in this
                // iteration, so needs_render is false, and there is no timeout.
                needs_render.then_some(pacer.duration_until_next_frame()),
            )?;
        }

        self.error_message.map_or(Ok(()), |s| Err(anyhow!(s)))
    }

    fn draw(&mut self, frame: &mut Frame) {
        let widget = AppWidget {
            current_tab_index: self.current_tab_index,
            view: &self.view,
            config: &self.config,
            hidden_instance: &self.hidden_instance,
            hidden_permanent: &self.hidden_permanent,
        };
        let mut widget_state = AppWidgetState {
            mouse_areas: &mut self.mouse_areas,
            tabs: &mut self.tabs,
            help_position: &mut self.help_position,
        };

        frame.render_stateful_widget(widget, frame.area(), &mut widget_state);
    }

    fn exit(&mut self, error_message: Option<String>) {
        self.exit = true;
        self.error_message = error_message;
    }

    fn stop_capture(&mut self, object_id: ObjectId) {
        self.capturing_objects.remove(&object_id);
        self.wirehose.node_capture_stop(object_id);
    }

    /// Node name wiremix (fork or upstream) gives its own peak-monitoring
    /// capture streams - see wirehose::stream::capture_node. Counting nodes
    /// with this name in the shared PipeWire graph state is what makes
    /// max_concurrent_captures_global possible without any custom IPC: the
    /// graph itself is already the shared, live state every instance reads.
    const CAPTURE_NODE_NAME: &'static str = "wiremix-capture";

    /// Total number of "wiremix-capture" nodes currently visible in the
    /// PipeWire graph, from any client - not just this instance's own
    /// capturing_objects. See the comment at its call site in
    /// start_capture() for the consistency caveats this implies.
    fn global_capture_count(&self) -> usize {
        self.state
            .nodes
            .values()
            .filter(|node| {
                node.props.node_name().map(String::as_str)
                    == Some(Self::CAPTURE_NODE_NAME)
            })
            .count()
    }

    fn start_capture(&mut self, object_id: ObjectId) {
        if self.config.lazy_capture
            && !self.visible_objects.contains(&object_id)
        {
            return;
        }

        // Hard cap on concurrent captures, enforced here (not just in the
        // rotation logic) so it can never be transiently exceeded - e.g. by
        // several nodes becoming capture-eligible at once before the next
        // rotation tick has a chance to run.
        if let Some(max) = self.config.max_concurrent_captures {
            if self.capturing_objects.len() >= max
                && !self.capturing_objects.contains(&object_id)
            {
                return;
            }
        }

        // Same idea, but counting *every* "wiremix-capture" node currently
        // visible in the PipeWire graph - including ones opened by other
        // wiremix instances - rather than just this instance's own
        // capturing_objects. This is necessarily best-effort: there's no
        // cross-process locking, so two instances racing to start a new
        // capture at the same moment can both observe room under the cap
        // and both proceed, transiently exceeding it until the graph state
        // settles. It also can't make non-cooperating processes (upstream
        // wiremix without this option, or any other client also named
        // "wiremix-capture") back off - it only makes instances that opt
        // into this setting considerate of each other and of themselves.
        //
        // global_capture_count() alone is not enough: it only reflects
        // captures that have round-tripped through the PipeWire server and
        // come back as a state update over wirehose's event channel, but
        // node_capture_start() (called at the bottom of this function) is
        // fire-and-forget - it queues a command for a separate PipeWire
        // thread and returns immediately, with no synchronous confirmation.
        // handle_events() drains and processes every currently-queued event
        // in one synchronous burst (see its `while let Ok(event) =
        // self.rx.try_recv()` loop), which is exactly when a flood of
        // CaptureEligibility::Eligible events (e.g. on startup, or when
        // lazy_capture reveals many nodes at once) calls start_capture()
        // for many objects back to back. None of those calls' own
        // node_capture_start() commands can possibly have round-tripped
        // back into self.state.nodes by the time the next call in the same
        // burst runs this check - so global_capture_count() reports the
        // same stale pre-burst number for the whole burst, and every call
        // sees "room under the cap" even after dozens of this instance's
        // own captures have already been started. Confirmed live: a single
        // instance with max_concurrent_captures_global = 20 and no other
        // instances contending ended up with 28 of its own active
        // captures, purely from this self-lag - not from any cross-instance
        // race, and not from CaptureEligibility::NeedsRestart (ruled out
        // separately: capture streams are properly disconnected on renewal
        // now that StreamRegistry::add_stream() calls disconnect() on the
        // stream it evicts, matching what StreamRegistry::remove() already
        // did - see that fix's own commit). self.capturing_objects.len()
        // has no such lag - it's updated synchronously the instant this
        // instance decides to capture something, before any round trip -
        // so folding it in as a floor closes the self-lag gap without
        // changing the inherent, already-documented cross-instance
        // best-effort behavior above.
        if let Some(max) = self.config.max_concurrent_captures_global {
            let estimate = self
                .global_capture_count()
                .max(self.capturing_objects.len());
            if estimate >= max && !self.capturing_objects.contains(&object_id) {
                return;
            }
        }

        if !self.config.capture_hidden
            && self.hidden_instance.contains(&object_id)
        {
            return;
        }

        let Some(node) = self.state.nodes.get(&object_id) else {
            return;
        };

        // Evaluated directly against hidden_permanent_matchers, not the
        // cached hidden_permanent set: during startup, the initial flood
        // of CaptureEligibility::Eligible events is handled before the
        // main loop's first state_dirty pass ever recomputes
        // hidden_permanent (see Self::run's "wait until ready" loop), so
        // relying on the cache here would let an already-permanently-
        // hidden node start capturing anyway on every fresh launch.
        if self
            .hidden_permanent_matchers
            .iter()
            .any(|matcher| matcher.matches(&self.state, node))
        {
            return;
        }

        if self
            .config
            .filters
            .iter()
            .any(|condition| condition.matches(&self.state, node))
        {
            return;
        }

        let Some(object_serial) = node.props.object_serial() else {
            return;
        };

        let capture_sink =
            node.props
                .media_class()
                .as_ref()
                .is_some_and(|media_class| {
                    media_class::is_sink(media_class)
                        || media_class::is_source(media_class)
                });

        self.capturing_objects.insert(object_id);
        self.wirehose.node_capture_start(
            node.object_id,
            *object_serial,
            capture_sink,
            Arc::clone(&node.peaks_dirty),
            Some(Arc::clone(&self.peak_processor)),
        );
    }

    /// If lazy capture is enabled, make sure visible nodes are captured and
    /// non-visible nodes are not.
    fn update_capturing(&mut self) {
        if !self.config.lazy_capture {
            return;
        }

        let need_to_start: Vec<_> = self
            .visible_objects
            .intersection(&self.capturable_objects)
            .copied()
            .collect();
        for object_id in need_to_start {
            if !self.capturing_objects.contains(&object_id) {
                self.start_capture(object_id);
            }
        }

        let need_to_stop: Vec<_> = self
            .capturing_objects
            .difference(&self.visible_objects)
            .copied()
            .collect();
        for object_id in need_to_stop {
            self.stop_capture(object_id);
        }
    }

    /// How many rendered frames pass between capture rotation slides, when
    /// max_concurrent_captures limits capture to fewer than are eligible.
    /// Deliberately a multiple of the render cadence itself (see
    /// RenderPacer and rotate_capturing()'s call site) rather than an
    /// independent wall-clock timer of its own: rotation speed - and the
    /// PipeWire stream churn it costs - then scales automatically with
    /// whatever fps a user has configured, with no second unrelated timer
    /// to reason about. Every frame would create more stream churn than not
    /// rotating at all (see rotate_capturing()'s doc comment); every 3rd
    /// frame keeps swap rates to a handful per second even at high fps,
    /// while still giving near-real-time coverage at typical settings -
    /// e.g. at 10-20fps, sweeping through ~10 eligible objects at
    /// max_concurrent_captures=2 takes well under 3 seconds.
    const ROTATION_FRAME_INTERVAL: u32 = 3;

    /// If max_concurrent_captures is set and more objects are eligible for
    /// capture than that, periodically swap which subset is actually being
    /// captured so every eligible object eventually gets sampled instead of
    /// whichever ones happened to become eligible first (and then stay
    /// captured forever, starving everything else).
    ///
    /// Slides the window by exactly one object per tick, rather than
    /// jumping it forward by the full window size - so at most one capture
    /// starts and one stops per tick, and everything else already in the
    /// window is left alone. A full-window jump every tick would mean every
    /// currently-captured object goes stale for the whole interval and then
    /// *all* of them change at once; a one-at-a-time slide instead gives a
    /// continuous, staggered trickle where something is always freshly
    /// updated.
    ///
    /// Only ever called once per actually-rendered frame (see its call site
    /// in run()), so counting frames via frames_since_rotation is exact.
    fn rotate_capturing(&mut self) {
        let Some(max) = self.config.max_concurrent_captures else {
            return;
        };

        self.frames_since_rotation =
            self.frames_since_rotation.saturating_add(1);
        if self.frames_since_rotation < Self::ROTATION_FRAME_INTERVAL {
            return;
        }

        // Same eligibility rule start_capture()/update_capturing() already
        // use: scoped to on-screen objects under lazy_capture, otherwise
        // every capturable object regardless of visibility.
        let mut eligible: Vec<ObjectId> = if self.config.lazy_capture {
            self.visible_objects
                .intersection(&self.capturable_objects)
                .copied()
                .collect()
        } else {
            self.capturable_objects.iter().copied().collect()
        };

        if eligible.len() <= max {
            // Everything eligible already fits under the cap - nothing to
            // rotate. Leave frames_since_rotation alone (already at or past
            // the threshold) so a rotation isn't "owed" extra delay the
            // moment the eligible set grows past max again.
            return;
        }

        self.frames_since_rotation = 0;

        // Sorting gives a stable, deterministic rotation order across ticks
        // (HashSet iteration order isn't stable) so each tick advances
        // through the *same* sequence rather than picking an arbitrary new
        // subset every time.
        eligible.sort_unstable();

        let n = eligible.len();
        let start = self.capture_rotation_start % n;
        let window: HashSet<ObjectId> =
            (0..max.min(n)).map(|i| eligible[(start + i) % n]).collect();
        self.capture_rotation_start = (start + 1) % n;

        let need_to_stop: Vec<_> = self
            .capturing_objects
            .difference(&window)
            .copied()
            .collect();
        for object_id in need_to_stop {
            self.stop_capture(object_id);
        }

        let need_to_start: Vec<_> = window
            .difference(&self.capturing_objects)
            .copied()
            .collect();
        for object_id in need_to_start {
            self.start_capture(object_id);
        }
    }

    fn set_capture_eligibility(
        &mut self,
        capture_eligibility: CaptureEligibility,
    ) {
        if self.config.peaks == Peaks::Off {
            return;
        }

        match capture_eligibility {
            CaptureEligibility::Eligible(object_id) => {
                self.capturable_objects.insert(object_id);
                if !self.capturing_objects.contains(&object_id) {
                    self.start_capture(object_id);
                }
            }
            CaptureEligibility::NeedsRestart(object_id) => {
                self.capturable_objects.insert(object_id);
                self.start_capture(object_id);
            }
            CaptureEligibility::Ineligible(object_id) => {
                self.capturable_objects.remove(&object_id);
                self.stop_capture(object_id);
            }
        }
    }

    /// Handle events with optional timeout.
    /// Returns true if events were handled.
    fn handle_events(&mut self, timeout: Option<Duration>) -> Result<bool> {
        let mut were_events_handled = match timeout {
            Some(timeout) => match self.rx.recv_timeout(timeout) {
                Ok(event) => event.handle(self)?,
                Err(mpsc::RecvTimeoutError::Timeout) => return Ok(false),
                Err(e) => return Err(e.into()),
            },
            // Block on the next event.
            None => self.rx.recv()?.handle(self)?,
        };
        // Then handle the rest that are available.
        while let Ok(event) = self.rx.try_recv() {
            were_events_handled |= event.handle(self)?;
        }

        Ok(were_events_handled)
    }
}

struct RenderPacer {
    frame_duration: Duration,
    next_frame_time: Instant,
}

impl RenderPacer {
    fn new(fps: Option<f32>) -> Self {
        let frame_duration = fps.map_or(Default::default(), |fps| {
            Duration::from_secs_f32(1.0 / fps)
        });

        Self {
            frame_duration,
            next_frame_time: Instant::now(),
        }
    }

    fn is_time_to_render(&mut self) -> bool {
        let now = Instant::now();

        if now >= self.next_frame_time {
            if now > self.next_frame_time + self.frame_duration {
                // We're running behind, so reset the frame timing.
                self.next_frame_time = now + self.frame_duration;
            } else {
                self.next_frame_time += self.frame_duration;
            }

            return true;
        }

        false
    }

    fn duration_until_next_frame(&self) -> Duration {
        self.next_frame_time
            .saturating_duration_since(Instant::now())
    }
}

trait Handle {
    /// Handle some kind of event. Returns true if the event was handled which
    /// indicates that the UI needs to be redrawn.
    fn handle(self, app: &mut App) -> Result<bool>;
}

impl Handle for Event {
    fn handle(self, app: &mut App) -> Result<bool> {
        match self {
            Event::Input(event) => event.handle(app),
            Event::Pipewire(event) => event.handle(app),
        }
    }
}

impl Handle for crossterm::event::Event {
    fn handle(self, app: &mut App) -> Result<bool> {
        match self {
            CrosstermEvent::Key(event) => event.handle(app),
            CrosstermEvent::Mouse(event) => event.handle(app),
            CrosstermEvent::Resize(..) => Ok(true),
            _ => Ok(false),
        }
    }
}

impl Handle for KeyEvent {
    fn handle(self, app: &mut App) -> Result<bool> {
        if self.kind != KeyEventKind::Press {
            return Ok(false);
        }

        if let Some(&action) = app.config.keybindings.get(&self) {
            return action.handle(app);
        }

        Ok(false)
    }
}

impl Handle for Action {
    fn handle(self, app: &mut App) -> Result<bool> {
        if let Some(ref mut help_position) = app.help_position {
            match self {
                Action::MoveDown => {
                    *help_position = help_position.saturating_add(1);
                    return Ok(true);
                }
                Action::MoveUp => {
                    *help_position = help_position.saturating_sub(1);
                    return Ok(true);
                }
                Action::PageDown => {
                    *help_position =
                        help_position.saturating_add(Self::HELP_PAGE_STEP);
                    return Ok(true);
                }
                Action::PageUp => {
                    *help_position =
                        help_position.saturating_sub(Self::HELP_PAGE_STEP);
                    return Ok(true);
                }
                Action::MoveLast => {
                    // Clamped to the real bottom by HelpWidget::render() -
                    // see the "Fix help_position if we are scrolled beyond
                    // the bottom of the list" comment there.
                    *help_position = u16::MAX;
                    return Ok(true);
                }
                Action::MoveFirst => {
                    *help_position = 0;
                    return Ok(true);
                }
                Action::ActivateDropdown
                | Action::CloseDropdown
                | Action::Help => {
                    // Close the help menu
                    app.help_position = None;
                    return Ok(true);
                }
                Action::Exit => {
                    app.exit(None);
                    return Ok(true);
                }
                _ => {
                    return Ok(false);
                }
            }
        }

        match self {
            Action::SelectTab(index) => {
                if index < app.tabs.len() {
                    app.current_tab_index = index;
                }
            }
            Action::MoveDown => {
                current_list!(app).down(&app.view);
            }
            Action::MoveUp => {
                current_list!(app).up(&app.view);
            }
            Action::PageDown => {
                current_list!(app).page_down(&app.view);
            }
            Action::PageUp => {
                current_list!(app).page_up(&app.view);
            }
            Action::MoveFirst => {
                current_list!(app).first(&app.view);
            }
            Action::MoveLast => {
                current_list!(app).last(&app.view);
            }
            Action::TabLeft => {
                app.current_tab_index = app
                    .current_tab_index
                    .checked_sub(1)
                    .unwrap_or(app.tabs.len() - 1)
            }
            Action::TabRight => {
                app.current_tab_index =
                    (app.current_tab_index + 1) % app.tabs.len()
            }
            Action::CloseDropdown => {
                current_list!(app).dropdown_close();
            }
            Action::ActivateDropdown => {
                current_list!(app).dropdown_activate(&app.view);
            }
            Action::SetTarget(target) => {
                current_list!(app).set_target(&app.view, target);
            }
            Action::SelectObject(object_id) => {
                app.tabs[app.current_tab_index].list.selected = Some(object_id)
            }
            Action::ToggleMute => {
                current_list!(app).toggle_mute(&app.view);
            }
            Action::ToggleHiddenInstance => {
                if let Some(object_id) = current_list!(app).selected {
                    if app.hidden_instance.remove(&object_id) {
                        // Unhidden - hold onto the selection (the user
                        // is still looking at this item), but nothing
                        // proactively resumes a capture just because
                        // eligibility didn't change, so re-trigger it
                        // here if it's still capturable. Skipped when
                        // capture_hidden is on, since the capture was
                        // never stopped in the first place.
                        if !app.config.capture_hidden
                            && app.capturable_objects.contains(&object_id)
                        {
                            app.start_capture(object_id);
                        }
                    } else {
                        app.hidden_instance.insert(object_id);
                        // start_capture()'s hidden_instance check only
                        // blocks new captures - an already-running one
                        // needs to be stopped explicitly here. Skipped
                        // when capture_hidden is on, since hidden items
                        // should keep being monitored like regular ones.
                        if !app.config.capture_hidden {
                            app.stop_capture(object_id);
                        }
                        // Release the selection rather than leave it
                        // pinned to an item that's about to sink to the
                        // bottom of the list - move it to whatever's
                        // next in line instead.
                        current_list!(app)
                            .release_hidden_selection(&app.view, object_id);
                    }
                    // Hiding/unhiding changes list ordering, which is
                    // computed in View::from() - force a rebuild.
                    app.state_dirty = true;
                }
            }
            Action::ToggleHiddenPermanent => {
                if let Some(object_id) = current_list!(app).selected {
                    let Some(node) = app.state.nodes.get(&object_id) else {
                        return Ok(false);
                    };

                    if app.hidden_permanent.contains(&object_id) {
                        // Unhiding: drop any matcher(s) that currently
                        // match this node, rather than tracking which
                        // matcher created which hide (there's no 1:1
                        // mapping once matchers can be hand-edited in the
                        // state file, or match more than one node).
                        app.hidden_permanent_matchers.retain(|matcher| {
                            !matcher.matches(&app.state, node)
                        });
                    } else if let Some(name) = node.props.node_name() {
                        app.hidden_permanent_matchers
                            .push(MatchCondition::from_node_name(name));
                    } else {
                        // No node.name to build a durable matcher from -
                        // nothing to persist, so there's nothing this
                        // action can do for this node.
                        return Ok(false);
                    }

                    app.recompute_hidden_permanent();

                    if app.hidden_permanent.contains(&object_id) {
                        app.stop_capture(object_id);
                    } else if app.capturable_objects.contains(&object_id) {
                        app.start_capture(object_id);
                    }

                    app.save_hidden_state();
                    app.state_dirty = true;
                }
            }
            Action::SetAbsoluteVolume(volume) => {
                let max = app
                    .config
                    .enforce_max_volume
                    .then_some(app.config.max_volume_percent);
                current_list!(app).set_absolute_volume(&app.view, volume, max);
                return Ok(current_list!(app)
                    .set_absolute_volume(&app.view, volume, max));
            }
            Action::SetRelativeVolume(volume) => {
                // Relative decreases have no maximum.
                let max = (volume > 0.0 && app.config.enforce_max_volume)
                    .then_some(app.config.max_volume_percent);
                return Ok(current_list!(app)
                    .set_relative_volume(&app.view, volume, max));
            }
            Action::SetDefault => {
                current_list!(app).set_default(&app.view);
            }
            Action::Exit => {
                app.exit(None);
            }
            Action::Nothing => {
                // Did nothing
                return Ok(false);
            }
            Action::Help => {
                // Activate the help menu
                app.help_position = Some(0);
            }
        }

        Ok(true)
    }
}

impl Handle for MouseEvent {
    fn handle(self, app: &mut App) -> Result<bool> {
        match self.kind {
            MouseEventKind::Down(MouseButton::Left) => {
                app.drag_row = Some(self.row)
            }
            MouseEventKind::Up(MouseButton::Left) => app.drag_row = None,
            _ => {}
        }

        let actions = app
            .mouse_areas
            .iter()
            .rev()
            .find(|(rect, kinds, _)| {
                rect.contains(Position {
                    x: self.column,
                    y: app.drag_row.unwrap_or(self.row),
                }) && kinds.contains(&self.kind)
            })
            .map(|(_, _, action)| action.clone())
            .into_iter()
            .flatten();

        let mut handled_action = false;
        for action in actions {
            handled_action = true;
            let _ = action.handle(app);
        }

        Ok(handled_action)
    }
}

impl Handle for PipewireEvent {
    fn handle(self, app: &mut App) -> Result<bool> {
        match self {
            PipewireEvent::Ready => {
                app.is_ready = true;
                Ok(true)
            }
            PipewireEvent::Error(message) => message.handle(app),
            PipewireEvent::State(event) => event.handle(app),
            PipewireEvent::HiddenStateChanged => {
                app.apply_file_hidden_state_change();
                Ok(true)
            }
        }
    }
}

impl Handle for StateEvent {
    fn handle(self, app: &mut App) -> Result<bool> {
        // Peaks are shared between state and view, so no update is necessary.
        app.state_dirty = !matches!(&self, StateEvent::NodePeaksDirty { .. });

        // Determine if any on-screen objects are affected by this event.
        // Generally we only need to check the event's object ID, but there are
        // some special cases.
        let visible_affected = self
            .affected_objects(&app.state)
            .iter()
            .any(|object| app.visible_objects.contains(object));

        for capture_eligibility in app.state.update(self) {
            app.set_capture_eligibility(capture_eligibility);
        }

        Ok(visible_affected)
    }
}

impl Handle for PipewireError {
    fn handle(self, app: &mut App) -> Result<bool> {
        // These errors don't seem to be fatal, so ignore them.
        // In debug builds, exit and log the error. In the event that we caused
        // the error, it will be helpful to know.
        if cfg!(debug_assertions) {
            app.exit(Some(self));
            return Ok(true);
        }

        Ok(false)
    }
}

pub struct AppWidget<'a, 'b> {
    current_tab_index: usize,
    view: &'a View<'b>,
    config: &'a Config,
    hidden_instance: &'a HashSet<ObjectId>,
    hidden_permanent: &'a HashSet<ObjectId>,
}

pub struct AppWidgetState<'a> {
    mouse_areas: &'a mut Vec<MouseArea>,
    tabs: &'a mut Vec<Tab>,
    help_position: &'a mut Option<u16>,
}

impl<'a> StatefulWidget for AppWidget<'a, '_> {
    type State = AppWidgetState<'a>;

    fn render(self, area: Rect, buf: &mut Buffer, state: &mut Self::State) {
        let layout = Layout::default()
            .direction(Direction::Vertical)
            .constraints([
                Constraint::Min(0),    // list_area
                Constraint::Length(1), // menu_area
            ])
            .split(area);
        let list_area = layout[0];
        let menu_area = layout[1];

        let constraints: Vec<_> = state
            .tabs
            .iter()
            .map(|tab| Constraint::Length(tab.title.len() as u16 + 2))
            .collect();

        let menu_areas = Layout::default()
            .direction(Direction::Horizontal)
            .constraints(constraints)
            .split(menu_area);

        for (i, tab) in state.tabs.iter().enumerate() {
            let title_line = if i == self.current_tab_index {
                Line::from(vec![
                    Span::styled(
                        &self.config.char_set.tab_marker_left,
                        self.config.theme.tab_marker,
                    ),
                    Span::styled(&tab.title, self.config.theme.tab_selected),
                    Span::styled(
                        &self.config.char_set.tab_marker_right,
                        self.config.theme.tab_marker,
                    ),
                ])
            } else {
                Line::from(Span::styled(
                    format!(" {} ", tab.title),
                    self.config.theme.tab,
                ))
            };
            title_line.render(menu_areas[i], buf);

            state.mouse_areas.push((
                menu_areas[i],
                smallvec![MouseEventKind::Down(MouseButton::Left)],
                smallvec![Action::SelectTab(i)],
            ));
        }

        let mut widget = ObjectListWidget {
            object_list: &mut state.tabs[self.current_tab_index].list,
            view: self.view,
            config: self.config,
            hidden_instance: self.hidden_instance,
            hidden_permanent: self.hidden_permanent,
        };
        widget.render(list_area, buf, state.mouse_areas);

        // Render the help menu if it's open
        if let Some(ref mut help_position) = state.help_position {
            // Ignore any mouse actions on the lower area
            state.mouse_areas.clear();
            // Close the help menu if clicked anywhere outside
            state.mouse_areas.push((
                area,
                smallvec![MouseEventKind::Down(MouseButton::Left)],
                smallvec![Action::Help],
            ));

            let width: u16 = self
                .config
                .help
                .widths
                .iter()
                .fold(HelpWidget::base_width(), |acc, &x| acc.saturating_add(x))
                .try_into()
                .unwrap_or(u16::MAX);
            let [help_area] = Layout::horizontal([Constraint::Max(width)])
                .flex(Flex::Center)
                .areas(list_area);
            // Fit to the number of help text rows, or 80% of the area if they
            // don't all fit
            let height: u16 = self
                .config
                .help
                .rows
                .len()
                .saturating_add(2)
                .try_into()
                .unwrap_or(u16::MAX)
                .min(((help_area.height as f32) * 0.90) as u16);
            let [help_area] = Layout::vertical([Constraint::Length(height)])
                .flex(Flex::Center)
                .areas(help_area);

            Clear.render(help_area, buf);

            HelpWidget {
                config: self.config,
            }
            .render(
                help_area,
                buf,
                &mut HelpWidgetState {
                    mouse_areas: state.mouse_areas,
                    help_position,
                },
            );
        }
    }
}

